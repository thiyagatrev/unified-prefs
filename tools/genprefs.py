#!/usr/bin/env python3
"""Generates the 200 UnifiedPrefs preferences, the Kotlin key registry and old-store fixtures.

Usage:
  python3 -I tools/genprefs.py --kotlin <GeneratedKeys.kt>
  python3 -I tools/genprefs.py --profile <typical|heavy> --out build/genprefs
  python3 -I tools/genprefs.py --self-check

Standard library only. KB = 1024 bytes, MB = 1024 * 1024 bytes.
sizes.txt holds the total UTF-8 bytes of all string values plus all set elements.
"""
import argparse
import base64
import json
import os
import plistlib
import random
import re
import struct
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

SEED = 20261112
HEADER = "// GENERATED by tools/genprefs.py — do not edit."
KB = 1024
MB = 1024 * 1024

# (type, count, name prefix); the order is the generator's order.
SPEC = [
    ("bool", 70, "feature_flag_"),
    ("int", 40, "counter_"),
    ("long", 24, "last_sync_ts_"),
    ("float", 16, "ratio_"),
    ("double", 8, "geo_coord_"),
    ("short", 30, "label_"),
    ("medium", 6, "token_"),
    ("large", 2, "cached_response_"),
    ("set", 4, "tag_set_"),
]
TAGS = {"bool": 1, "int": 2, "long": 3, "float": 4, "double": 5, "string": 6, "set": 7}
CHECK_TYPE = {"short": "string", "medium": "string", "large": "string"}
# Large-string target sizes: within the brief's 10-40 KB (typical) and 1.0-1.5 MB (heavy).
LARGE_RANGE = {"typical": (16 * KB, 38 * KB), "heavy": (int(1.0 * MB), int(1.45 * MB))}
SIZE_RANGE = {"typical": (30 * KB, 120 * KB), "heavy": (2 * MB, int(3.2 * MB))}

SPECIALS = [
    "", "a<b>c", "x&y", 'say "hi"', "line1\nline2", "\U0001F64F\U0001F389", "நன்றி",
    "நன்றி \U0001F64F <a&b>", "tab\tand 'quote'", "  padded  ", "café üñî",
    "]]> &amp; &lt;",
]
WORDS = ("alpha beta gamma delta sigma omega pixel orbit river stone cloud ember maple quartz lunar "
         "solar harbor meadow summit tundra violet willow zephyr").split()
NON_LATIN = ["வணக்கம்", "நன்றி", "தமிழ்"]
EMOJI = ["\U0001F64F", "\U0001F680", "\U0001F389", "✨"]
TAG_WORDS = ["beta", "gold", "new", "sync", "pinned", "cache", "ui", "a", "z"]


# Longs other than the three extremes are millisecond timestamps between 2015 and 2030.
TS_MIN_MS = 1_420_070_400_000
TS_MAX_MS = 1_893_456_000_000


def f32(x):
    return struct.unpack(">f", struct.pack(">f", x))[0]


def short_string(rng, i):
    if i < len(SPECIALS):
        return SPECIALS[i]
    parts = [rng.choice(WORDS) for _ in range(rng.randint(1, 5))]
    if rng.random() < 0.25:
        parts.append(rng.choice(NON_LATIN))
    if rng.random() < 0.2:
        parts.append(rng.choice(EMOJI))
    return " ".join(parts)


def medium_string(rng, i):
    if i % 2 == 0:
        raw = bytes(rng.getrandbits(8) for _ in range(rng.randint(800, 3000)))
        return base64.b64encode(raw).decode("ascii")
    obj = {"user": rng.choice(WORDS), "scopes": [rng.choice(WORDS) for _ in range(rng.randint(2, 8))],
           "exp": rng.randint(1_700_000_000, 1_900_000_000), "note": rng.choice(NON_LATIN) + " " + rng.choice(EMOJI),
           "blob": base64.b64encode(bytes(rng.getrandbits(8) for _ in range(rng.randint(800, 2700)))).decode()}
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def large_string(rng, target):
    items = []
    size = 2
    n = 0
    while size < target:
        item = {"id": n, "title": " ".join(rng.choice(WORDS) for _ in range(rng.randint(2, 6)))
                + (" " + rng.choice(NON_LATIN) if rng.random() < 0.1 else ""),
                "tags": [rng.choice(WORDS) for _ in range(rng.randint(1, 4))],
                "score": round(rng.random() * 100, 3)}
        text = json.dumps(item, ensure_ascii=False, separators=(",", ":"))
        items.append(text)
        size += len(text.encode("utf-8")) + 1
        n += 1
    return "[" + ",".join(items) + "]"


def generate(profile):
    """Returns the ordered list of keys: dicts with name, kind, value, default."""
    rng = random.Random(SEED)
    lo, hi = LARGE_RANGE[profile]
    big_rng = random.Random("%d-large-%s" % (SEED, profile))
    keys = []
    for kind, count, prefix in SPEC:
        for i in range(count):
            if kind == "bool":
                value, default = rng.random() < 0.5, False
            elif kind == "int":
                value = [-2147483648, 2147483647, 0][i] if i < 3 else rng.randint(-2**31, 2**31 - 1)
                default = 0
            elif kind == "long":
                value = [-2**63, 2**63 - 1, 0][i] if i < 3 else rng.randint(TS_MIN_MS, TS_MAX_MS)
                default = 0
            elif kind == "float":
                value = f32(rng.uniform(-1000.0, 1000.0) if i % 2 else rng.random())
                default = 0.0
            elif kind == "double":
                value, default = rng.uniform(-180.0, 180.0), 0.0
            elif kind == "short":
                value, default = short_string(rng, i), ""
            elif kind == "medium":
                value, default = medium_string(rng, i), ""
            elif kind == "large":
                value, default = large_string(big_rng, big_rng.randint(lo, hi)), ""
            else:
                value, size = set(), rng.randint(3, 50)
                while len(value) < size:
                    value.add(rng.choice(TAG_WORDS) + str(rng.randint(0, 99)))
                default = set()
            keys.append({"name": "%s%04d" % (prefix, i), "kind": kind, "value": value, "default": default})
    return keys


# ---------- checksum (contract R4) ----------

def fnv1a(data, h=0xcbf29ce484222325):
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def checksum(entries):
    """entries: iterable of (name, kind, value); kind is a SPEC kind or 'string'."""
    buf = bytearray()
    for name, kind, value in sorted(entries, key=lambda e: e[0]):
        kind = CHECK_TYPE.get(kind, kind)
        buf += name.encode("utf-8") + b"\x00" + bytes([TAGS[kind]])
        if kind == "bool":
            buf += bytes([1 if value else 0])
        elif kind == "int":
            buf += struct.pack(">i", value)
        elif kind == "long":
            buf += struct.pack(">q", value)
        elif kind == "float":
            buf += struct.pack(">f", value)
        elif kind == "double":
            buf += struct.pack(">d", value)
        elif kind == "string":
            raw = value.encode("utf-8")
            buf += struct.pack(">I", len(raw)) + raw
        else:
            buf += struct.pack(">I", len(value))
            for e in sorted(value):
                buf += e.encode("utf-8") + b"\x00"
    return "%016x" % fnv1a(bytes(buf))


def key_checksum(keys, android):
    return checksum([(k["name"], k["kind"], k["default"] if android and k["kind"] == "double" else k["value"])
                     for k in keys])


# ---------- outputs ----------

def text(s):
    """Element text escaped as Android's FastXmlSerializer writes it: & < > " and chars below 0x20."""
    out = escape(s, {'"': "&quot;"})
    return "".join("&#%d;" % ord(c) if ord(c) < 0x20 else c for c in out)


def attr(s):
    return escape(s, {'"': "&quot;"})


def android_xml(keys):
    out = ["<?xml version='1.0' encoding='utf-8' standalone='yes' ?>", "<map>",
           '    <boolean name="dark_mode" value="true" />',
           '    <int name="launch_count" value="3" />',
           '    <string name="user_name">Asha</string>']
    for k in keys:
        n, v, kind = attr(k["name"]), k["value"], k["kind"]
        if kind == "double":
            continue
        if kind == "bool":
            out.append('    <boolean name="%s" value="%s" />' % (n, "true" if v else "false"))
        elif kind in ("int", "long"):
            out.append('    <%s name="%s" value="%d" />' % (kind, n, v))
        elif kind == "float":
            out.append('    <float name="%s" value="%s" />' % (n, repr(v)))
        elif kind == "set":
            out.append('    <set name="%s">' % n)
            for e in sorted(v):
                out.append("        <string>%s</string>" % text(e))
            out.append("    </set>")
        else:
            out.append('    <string name="%s">%s</string>' % (n, text(v)))
    out.append("</map>")
    return ("\n".join(out) + "\n").encode("utf-8")


def ios_dict(keys):
    d = {"isDarkMode": True, "launchCount": 3, "userName": "Asha"}
    for k in keys:
        v = k["value"]
        d[k["name"]] = sorted(v) if k["kind"] == "set" else v
    return d


def ios_plist(keys):
    return plistlib.dumps(ios_dict(keys), fmt=plistlib.FMT_BINARY, sort_keys=True)


def kotlin_literal(kind):
    return {"bool": "false", "int": "0", "long": "0L", "float": "0f", "double": "0.0",
            "set": "emptySet()"}.get(kind, '""')


def kotlin_type(kind):
    return {"bool": "BoolKey", "int": "IntKey", "long": "LongKey", "float": "FloatKey", "double": "DoubleKey",
            "set": "StringSetKey"}.get(kind, "StringKey")


def kotlin_file(keys):
    lines = [HEADER, "package com.example.unifiedprefs.storage", "", "object GeneratedKeys {"]
    for k in keys:
        lines.append('    val %s = %s("%s", %s)' % (k["name"], kotlin_type(k["kind"]), k["name"],
                                                    kotlin_literal(k["kind"])))
    lines.append("    val all: List<PrefKey> = listOf(")
    lines += ["        %s," % k["name"] for k in keys]
    lines += ["    )", "}", ""]
    return "\n".join(lines).encode("utf-8")


def value_bytes(keys):
    total = 0
    for k in keys:
        v = k["value"]
        if k["kind"] in ("short", "medium", "large"):
            total += len(v.encode("utf-8"))
        elif k["kind"] == "set":
            total += sum(len(e.encode("utf-8")) for e in v)
    return total


def write_profile(profile, out):
    keys = generate(profile)
    d = os.path.join(out, profile)
    os.makedirs(d, exist_ok=True)
    files = {
        "app_prefs.xml": android_xml(keys),
        "legacy.plist": ios_plist(keys),
        "expected-android.txt": (key_checksum(keys, True) + "\n").encode(),
        "expected-ios.txt": (key_checksum(keys, False) + "\n").encode(),
        "sizes.txt": ("%d\n" % value_bytes(keys)).encode(),
    }
    for name, data in files.items():
        with open(os.path.join(d, name), "wb") as f:
            f.write(data)
    print("%s: %d value bytes -> %s" % (profile, value_bytes(keys), d))


# ---------- self-check ----------

def parse_xml(data):
    got = {}
    for el in ET.fromstring(data):
        name = el.get("name")
        if el.tag == "boolean":
            got[name] = el.get("value") == "true"
        elif el.tag in ("int", "long"):
            got[name] = int(el.get("value"))
        elif el.tag == "float":
            got[name] = float(el.get("value"))
        elif el.tag == "string":
            got[name] = el.text or ""
        elif el.tag == "set":
            got[name] = {s.text or "" for s in el}
        else:
            raise AssertionError("unknown element " + el.tag)
    return got


def check_counts():
    keys = generate("typical")
    for kind, count, _ in SPEC:
        n = sum(1 for k in keys if k["kind"] == kind)
        assert n == count, "%s: %d != %d" % (kind, n, count)
    assert len(keys) == 200


def check_names():
    names = [k["name"] for k in generate("typical")]
    assert len(set(names)) == len(names), "duplicate names"
    assert all(n.isascii() for n in names)


def check_deterministic():
    for p in ("typical", "heavy"):
        a, b = generate(p), generate(p)
        assert android_xml(a) == android_xml(b), "xml differs"
        assert ios_plist(a) == ios_plist(b), "plist differs"
        assert kotlin_file(a) == kotlin_file(b), "kotlin differs"
    assert kotlin_file(generate("typical")) == kotlin_file(generate("heavy")), "kotlin differs by profile"


def check_xml_roundtrip():
    for p in ("typical", "heavy"):
        keys = generate(p)
        got = parse_xml(android_xml(keys))
        assert got["dark_mode"] is True and got["launch_count"] == 3 and got["user_name"] == "Asha"
        for k in keys:
            if k["kind"] == "double":
                assert k["name"] not in got
            else:
                assert got[k["name"]] == k["value"], "mismatch " + k["name"]
        assert len(got) == 192 + 3


def check_plist_roundtrip():
    keys = generate("typical")
    got = plistlib.loads(ios_plist(keys))
    assert got["isDarkMode"] is True and got["launchCount"] == 3 and got["userName"] == "Asha"
    for k in keys:
        want = sorted(k["value"]) if k["kind"] == "set" else k["value"]
        assert got[k["name"]] == want, "mismatch " + k["name"]
    assert len(got) == 203


def check_floats():
    keys = generate("typical")
    root = ET.fromstring(android_xml(keys))
    want = {k["name"]: k["value"] for k in keys if k["kind"] == "float"}
    n = 0
    for el in root.iter("float"):
        assert struct.pack(">f", float(el.get("value"))) == struct.pack(">f", want[el.get("name")]), el.get("name")
        n += 1
    assert n == 16


def check_sizes():
    for p in ("typical", "heavy"):
        s = value_bytes(generate(p))
        lo, hi = SIZE_RANGE[p]
        assert lo <= s <= hi, "%s size %d not in [%d, %d]" % (p, s, lo, hi)


def check_vector():
    vec = [("tv_bool", "bool", True), ("tv_double", "double", -0.1), ("tv_float", "float", 1.5),
           ("tv_int", "int", -2147483648), ("tv_long", "long", 1731400000000), ("tv_set", "set", {"b", "a", "c"}),
           ("tv_str", "short", "நன்றி \U0001F64F <a&b>"), ("tv_unset", "short", "dflt")]
    got = checksum(vec)
    assert got == "226e901c9354c740", got
    assert checksum([]) == "cbf29ce484222325"


def check_specials():
    shorts = [k["value"] for k in generate("typical") if k["kind"] == "short"]
    for ch in ("<", "&", '"', "\n"):
        assert any(ch in s for s in shorts), "no short string with " + repr(ch)
    assert any(ord(c) > 0xFFFF for s in shorts for c in s), "no emoji"
    assert any("஀" <= c <= "௿" for s in shorts for c in s), "no non-Latin text"
    assert "" in shorts, "no empty string"


def check_extremes():
    keys = generate("typical")
    ints = {k["value"] for k in keys if k["kind"] == "int"}
    longs = {k["value"] for k in keys if k["kind"] == "long"}
    assert {-2147483648, 2147483647, 0} <= ints
    assert {-2**63, 2**63 - 1} <= longs


def check_sets_ascii():
    for k in generate("typical"):
        if k["kind"] == "set":
            assert all(e.isascii() for e in k["value"])


def check_xml_escapes_like_android():
    # Android's FastXmlSerializer writes '"' in text as &quot; and characters below 0x20 as &#N;.
    # A fixture with raw quotes is a smaller, cheaper file than any real user has.
    for profile in ("typical", "heavy"):
        text = android_xml(generate(profile)).decode("utf-8")
        for body in re.findall(r"<string(?: name=\"[^\"]*\")?>(.*?)</string>", text, re.S):
            assert '"' not in body, "raw quote in string text (%s)" % profile
            assert not any(ord(c) < 0x20 for c in body), "raw control char in string text (%s)" % profile


def check_medium_sizes():
    for k in generate("typical"):
        if k["kind"] == "medium":
            n = len(k["value"].encode("utf-8"))
            assert 1024 <= n <= 4096, "%s is %d bytes" % (k["name"], n)


def check_set_sizes():
    for k in generate("typical"):
        if k["kind"] == "set":
            assert 3 <= len(k["value"]) <= 50, "%s has %d entries" % (k["name"], len(k["value"]))


def check_longs_are_timestamps():
    extremes = {-2**63, 2**63 - 1, 0}
    for k in generate("typical"):
        if k["kind"] == "long" and k["value"] not in extremes:
            assert TS_MIN_MS <= k["value"] <= TS_MAX_MS, "%s=%d is not a 2015-2030 ms timestamp" % (k["name"], k["value"])


CHECKS = [("countsMatch", check_counts), ("namesUniqueAndAscii", check_names), ("deterministic", check_deterministic),
          ("xmlRoundTrip", check_xml_roundtrip), ("plistRoundTrip", check_plist_roundtrip),
          ("floatsRoundTrip", check_floats), ("sizesInRange", check_sizes), ("checksumVector", check_vector),
          ("stringsCoverSpecials", check_specials), ("intExtremes", check_extremes), ("setsAscii", check_sets_ascii),
          ("xmlEscapesLikeAndroid", check_xml_escapes_like_android), ("mediumStrings1To4KB", check_medium_sizes),
          ("setsHave3To50Entries", check_set_sizes), ("longsAreTimestamps", check_longs_are_timestamps)]


def self_check():
    ok = 0
    for name, fn in CHECKS:
        try:
            fn()
            ok += 1
            print("ok   " + name)
        except Exception as e:  # noqa: BLE001
            print("FAIL %s: %r" % (name, e))
    print("self-check: %d/%d ok" % (ok, len(CHECKS)))
    return ok == len(CHECKS)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kotlin")
    ap.add_argument("--profile", choices=["typical", "heavy"])
    ap.add_argument("--out", default="build/genprefs")
    ap.add_argument("--self-check", action="store_true")
    a = ap.parse_args()
    if a.self_check:
        return 0 if self_check() else 1
    if not (a.kotlin or a.profile):
        ap.error("nothing to do")
    if a.kotlin:
        with open(a.kotlin, "wb") as f:
            f.write(kotlin_file(generate("typical")))
        print("wrote " + a.kotlin)
    if a.profile:
        write_profile(a.profile, a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
